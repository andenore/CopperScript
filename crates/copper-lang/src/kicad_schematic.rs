//! The deterministic KiCad 8 schematic backend (`pcbir.backends.kicad`) and
//! its project writer (`pcbir.backends.kicad_project.write_kicad_schematic`).
//!
//! A flat, single-sheet schematic: symbols are generated from the part
//! definitions and embedded, and every coordinate and UUID is a pure function
//! of the design, computed with Python's float arithmetic in Python's order.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use copper_json::{Dumps, Object, Value, encode_str};
use indexmap::IndexMap;
use num_bigint::BigUint;
use sha2::{Digest, Sha256};

use crate::elaborate::elaborate;
use crate::model::{
    Board, ComponentInstance, ComponentValue, DeviceDefinition, Direction, DriveMode, ElectricalProfile, Endpoint,
    PackagePinDefinition, PartDefinition, SignalDomain,
};
use crate::modes::pins_bonded_to_pad;
use crate::paths;

const KICAD_SCHEMATIC_FORMAT: &str = "20231120";
const KICAD_TARGET_VERSION: &str = "8.0";
const UUID_SEED: &[u8] = b"CopperScript KiCad schematic backend v0.1\0";
const PAGE: &str = "A4";
const COLUMNS: usize = 3;
const PITCH: f64 = 2.54;

/// One generated file.
#[derive(Clone, Debug, PartialEq)]
pub struct Artifact {
    pub name: String,
    pub content: String,
}

/// The schematic, its symbol library, the library table and the project.
#[derive(Clone, Debug, PartialEq)]
pub struct SchematicManifest {
    pub target_version: &'static str,
    pub artifacts: Vec<Artifact>,
    pub warnings: Vec<String>,
}

struct PinLayout<'a> {
    pin: &'a PackagePinDefinition,
    electrical_type: &'static str,
    x: f64,
    y: f64,
    angle: i32,
    outward: i32,
}

struct PartSymbol<'a> {
    part: &'a PartDefinition,
    library_id: String,
    entry_name: String,
    pins: Vec<PinLayout<'a>>,
    half_width: f64,
    half_height: f64,
}

/// `KiCadSchematicBackend().generate(board)`; an error is the backend's
/// `ValueError` message.
pub fn generate(board: &Board) -> Result<SchematicManifest, String> {
    let flat = elaborate(board)?;
    let content = render(board, &flat.library, &flat.devices, &flat.components, &flat.nets)?;
    let safe = safe_name(&board.name);
    let used: BTreeSet<&str> = flat.components.iter().map(|component| component.part.as_str()).collect();
    let symbols: Vec<PartSymbol<'_>> =
        used.iter().map(|name| part_symbol(&flat.library[*name], &flat.devices)).collect();
    let grouped = symbols.iter().any(|symbol| !symbol.part.internal_pad_groups.is_empty());
    let mut library_lines = vec![
        "(kicad_symbol_lib".to_owned(),
        format!("  (version {})", if grouped { "20251024" } else { "20231120" }),
        "  (generator \"copperscript\")".to_owned(),
    ];
    for symbol in &symbols {
        library_lines.extend(library_symbol_lines(symbol, true));
    }
    library_lines.push(")".to_owned());
    let library_content = library_lines.join("\n") + "\n";
    let library_name = format!("CopperScript_{}.kicad_sym", &hex(&Sha256::digest(library_content.as_bytes()))[..16]);
    let table = format!(
        "(sym_lib_table\n  (version 7)\n  (lib (name \"CopperScript\")(type \"KiCad\")(uri \"${{KIPRJMOD}}/{library_name}\")\
         (options \"\")(descr \"Generated by CopperScript\"))\n)\n"
    );
    let project_name = format!("{safe}.kicad_pro");
    let warnings = if board.module_instances.is_empty() {
        Vec::new()
    } else {
        vec![
            "Hierarchy was elaborated into a flat single-sheet schematic; the CopperScript IR remains hierarchical."
                .to_owned(),
        ]
    };
    let target_version =
        if flat.components.iter().any(|component| !flat.library[&component.part].internal_pad_groups.is_empty()) {
            "10.0"
        } else {
            KICAD_TARGET_VERSION
        };
    Ok(SchematicManifest {
        target_version,
        artifacts: vec![
            Artifact { name: format!("{safe}.kicad_sch"), content },
            Artifact { name: library_name, content: library_content },
            Artifact { name: "sym-lib-table".to_owned(), content: table },
            Artifact { name: project_name.clone(), content: project_json(&project_name) },
        ],
        warnings,
    })
}

/// `json.dumps({"meta": {"filename": name, "version": 1}}, indent=2) + "\n"`.
fn project_json(filename: &str) -> String {
    let mut meta = Object::new();
    meta.insert("filename".to_owned(), Value::from(filename));
    meta.insert("version".to_owned(), Value::Int(1.into()));
    let mut project = Object::new();
    project.insert("meta".to_owned(), Value::Object(meta));
    Dumps::new().indent(2).dumps(&Value::Object(project)) + "\n"
}

fn render(
    board: &Board,
    library: &IndexMap<String, PartDefinition>,
    devices: &IndexMap<String, DeviceDefinition>,
    components: &[ComponentInstance],
    nets: &[crate::model::Net],
) -> Result<String, String> {
    let mut components: Vec<&ComponentInstance> = components.iter().collect();
    components.sort_by(|a, b| a.reference.cmp(&b.reference));
    let used: BTreeSet<&str> = components.iter().map(|component| component.part.as_str()).collect();
    if let Some(missing) = used.iter().find(|name| !library.contains_key(**name)) {
        return Err(format!("cannot generate symbol for unknown part {}", copper_json::python_str_repr(missing)));
    }
    let symbols: IndexMap<&str, PartSymbol<'_>> =
        used.iter().map(|name| (*name, part_symbol(&library[*name], devices))).collect();
    let placements = place_components(&components, &symbols);
    let root_uuid = stable_uuid(&[&board.name, "root"]);
    let index: IndexMap<&str, &ComponentInstance> =
        components.iter().map(|component| (component.reference.as_str(), *component)).collect();
    let mut endpoint_nets: IndexMap<Endpoint, &str> = IndexMap::new();
    for net in nets {
        for endpoint in &net.endpoints {
            let component = index.get(endpoint.component.as_str()).copied();
            let part = component.and_then(|component| library.get(&component.part));
            let physical = match (component, part) {
                (Some(component), Some(part)) => physical_pin_name(component, part, devices, &endpoint.pin),
                _ => None,
            };
            endpoint_nets.insert(
                Endpoint::new(&endpoint.component, physical.as_deref().unwrap_or(&endpoint.pin)),
                net.name.as_str(),
            );
        }
    }
    let grouped = symbols.values().any(|symbol| !symbol.part.internal_pad_groups.is_empty());
    let mut lines = vec![
        "(kicad_sch".to_owned(),
        format!("  (version {})", if grouped { "20250610" } else { KICAD_SCHEMATIC_FORMAT }),
        "  (generator \"copperscript\")".to_owned(),
        "  (generator_version \"0.1.0\")".to_owned(),
        format!("  (uuid \"{root_uuid}\")"),
        format!("  (paper {})", quote(PAGE)),
        "  (title_block".to_owned(),
        format!("    (title {})", quote(&board.name)),
        "    (comment 1 \"Generated by CopperScript; edit the .copper source\")".to_owned(),
        "  )".to_owned(),
        "  (lib_symbols".to_owned(),
    ];
    for symbol in symbols.values() {
        lines.extend(library_symbol_lines(symbol, false));
    }
    lines.push("  )".to_owned());
    for component in &components {
        let symbol = &symbols[component.part.as_str()];
        let (x, y) = placements[component.reference.as_str()];
        for layout in &symbol.pins {
            let endpoint = Endpoint::new(&component.reference, &layout.pin.name);
            let pin_x = x + layout.x;
            // Symbol-library Y points up; schematic-sheet Y points down.
            let pin_y = y - layout.y;
            let Some(net_name) = endpoint_nets.get(&endpoint) else {
                lines.extend(no_connect_lines(&board.name, &endpoint, pin_x, pin_y));
                continue;
            };
            let label_x = pin_x + f64::from(layout.outward) * PITCH;
            lines.extend(wire_lines(&board.name, &endpoint, pin_x, pin_y, label_x, pin_y));
            lines.extend(label_lines(&board.name, &endpoint, net_name, label_x, pin_y, layout.outward));
        }
    }
    for component in &components {
        let symbol = &symbols[component.part.as_str()];
        lines.extend(component_symbol_lines(
            &board.name,
            &root_uuid,
            component,
            symbol,
            placements[component.reference.as_str()],
        ));
    }
    lines.extend(
        ["  (sheet_instances", "    (path \"/\"", "      (page \"1\")", "    )", "  )", ")"].map(str::to_owned),
    );
    Ok(lines.join("\n") + "\n")
}

/// The package pin an endpoint names: a pin, or a unit terminal whose pad
/// exactly one active bond reaches.
fn physical_pin_name(
    component: &ComponentInstance,
    part: &PartDefinition,
    devices: &IndexMap<String, DeviceDefinition>,
    endpoint: &str,
) -> Option<String> {
    if part.pins.contains_key(endpoint) {
        return Some(endpoint.to_owned());
    }
    let (unit_name, terminal_name) = endpoint.split_once('.')?;
    let device = devices.get(part.device.as_deref().unwrap_or(""))?;
    let terminal = device.units.get(unit_name)?.terminals.get(terminal_name)?;
    match pins_bonded_to_pad(component, part, Some(device), &terminal.pad).as_slice() {
        [pin] => Some(pin.name.clone()),
        _ => None,
    }
}

fn part_symbol<'a>(part: &'a PartDefinition, devices: &IndexMap<String, DeviceDefinition>) -> PartSymbol<'a> {
    let digest = hex(&Sha256::digest(part.name.as_bytes()));
    let entry_name = format!("{}_{}", safe_name(&part.name), &digest[..8]);
    let mut ordered: Vec<&PackagePinDefinition> = part.pins.values().collect();
    ordered.sort_by_cached_key(|pin| pin_sort_key(&pin.number));
    let left_count = ordered.len().div_ceil(2);
    let (left, right) = ordered.split_at(left_count);
    let half_width = 7.62;
    let rows = left.len().max(right.len()).max(1) + 1;
    let half_height = f64::max(5.08, rows as f64 * PITCH / 2.0);
    let mut pins = Vec::with_capacity(ordered.len());
    for (index, pin) in left.iter().enumerate() {
        pins.push(PinLayout {
            pin,
            electrical_type: pin_electrical_type(part, pin, devices),
            x: -(half_width + 2.54),
            y: pin_y(index, left.len()),
            angle: 0,
            outward: -1,
        });
    }
    for (index, pin) in right.iter().enumerate() {
        pins.push(PinLayout {
            pin,
            electrical_type: pin_electrical_type(part, pin, devices),
            x: half_width + 2.54,
            y: pin_y(index, right.len()),
            angle: 180,
            outward: 1,
        });
    }
    PartSymbol { part, library_id: format!("CopperScript:{entry_name}"), entry_name, pins, half_width, half_height }
}

fn library_symbol_lines(symbol: &PartSymbol<'_>, standalone: bool) -> Vec<String> {
    let part = symbol.part;
    let footprint = part.footprints.first().map_or("", String::as_str);
    let datasheet = source_url(part);
    let description = part.manufacturer.clone().unwrap_or_else(|| format!("CopperScript part {}", part.name));
    let mut lines = vec![
        format!("    (symbol {}", quote(if standalone { &symbol.entry_name } else { &symbol.library_id })),
        "      (pin_names (offset 1.016))".to_owned(),
        "      (exclude_from_sim no)".to_owned(),
        format!("      (in_bom {})", yes_no(part.assembled)),
        "      (on_board yes)".to_owned(),
    ];
    if !part.internal_pad_groups.is_empty() && part.assembled {
        let groups: Vec<String> = part
            .internal_pad_groups
            .iter()
            .map(|group| format!("({})", group.numbers.iter().map(|n| quote(n)).collect::<Vec<_>>().join(" ")))
            .collect();
        lines.push("      (duplicate_pin_numbers_are_jumpers no)".to_owned());
        lines.push(format!("      (jumper_pin_groups {})", groups.join(" ")));
    }
    let (hw, hh) = (symbol.half_width, symbol.half_height);
    lines.extend(property_lines(6, "Reference", reference_prefix(part), -hw, -(hh + 2.54), false));
    lines.extend(property_lines(6, "Value", &part.name, -hw, hh + 2.54, false));
    lines.extend(property_lines(6, "Footprint", footprint, 0.0, 0.0, true));
    lines.extend(property_lines(6, "Datasheet", datasheet, 0.0, 0.0, true));
    lines.extend(property_lines(6, "Description", &description, 0.0, 0.0, true));
    lines.extend([
        format!("      (symbol {}", quote(&format!("{}_0_1", symbol.entry_name))),
        "        (rectangle".to_owned(),
        format!("          (start {} {})", number(-hw), number(-hh)),
        format!("          (end {} {})", number(hw), number(hh)),
        "          (stroke (width 0.254) (type default))".to_owned(),
        "          (fill (type background))".to_owned(),
        "        )".to_owned(),
        "      )".to_owned(),
        format!("      (symbol {}", quote(&format!("{}_1_1", symbol.entry_name))),
    ]);
    for layout in &symbol.pins {
        lines.extend([
            format!("        (pin {} line", layout.electrical_type),
            format!("          (at {} {} {})", number(layout.x), number(layout.y), layout.angle),
            "          (length 2.54)".to_owned(),
            format!("          (name {} (effects (font (size 1.27 1.27))))", quote(&layout.pin.name)),
            format!("          (number {} (effects (font (size 1.27 1.27))))", quote(&layout.pin.number)),
            "        )".to_owned(),
        ]);
    }
    lines.push("      )".to_owned());
    lines.push("    )".to_owned());
    lines
}

fn component_symbol_lines(
    board_name: &str,
    root_uuid: &str,
    component: &ComponentInstance,
    symbol: &PartSymbol<'_>,
    (x, y): (f64, f64),
) -> Vec<String> {
    let part = symbol.part;
    let symbol_uuid = stable_uuid(&[board_name, "symbol", &component.reference]);
    let value = component_value(component, part);
    let footprint = match component.footprint.as_deref() {
        Some(footprint) if !footprint.is_empty() => footprint,
        _ => part.footprints.first().map_or("", String::as_str),
    };
    let kicad_ref = kicad_reference(&component.reference);
    let (hw, hh) = (symbol.half_width, symbol.half_height);
    let mut lines = vec![
        "  (symbol".to_owned(),
        format!("    (lib_id {})", quote(&symbol.library_id)),
        format!("    (at {} {} 0)", number(x), number(y)),
        "    (unit 1)".to_owned(),
        "    (exclude_from_sim no)".to_owned(),
        format!("    (in_bom {})", yes_no(part.assembled)),
        "    (on_board yes)".to_owned(),
        "    (dnp no)".to_owned(),
        format!("    (uuid \"{symbol_uuid}\")"),
    ];
    lines.extend(property_lines(4, "Reference", &kicad_ref, x - hw, y - hh - 2.54, false));
    lines.extend(property_lines(4, "Value", &value, x - hw, y + hh + 2.54, false));
    lines.extend(property_lines(4, "Footprint", footprint, x, y, true));
    lines.extend(property_lines(4, "Datasheet", source_url(part), x, y, true));
    lines.extend(property_lines(4, "Description", "", x, y, true));
    if kicad_ref != component.reference {
        lines.extend(property_lines(4, "CopperScriptPath", &component.reference, x, y, true));
    }
    for layout in &symbol.pins {
        let pin_uuid = stable_uuid(&[board_name, "pin", &component.reference, &layout.pin.number]);
        lines.extend([
            format!("    (pin {}", quote(&layout.pin.number)),
            format!("      (uuid \"{pin_uuid}\")"),
            "    )".to_owned(),
        ]);
    }
    lines.extend([
        "    (instances".to_owned(),
        format!("      (project {}", quote(&safe_name(board_name))),
        format!("        (path \"/{root_uuid}\""),
        format!("          (reference {})", quote(&kicad_ref)),
        "          (unit 1)".to_owned(),
        "        )".to_owned(),
        "      )".to_owned(),
        "    )".to_owned(),
        "  )".to_owned(),
    ]);
    lines
}

fn property_lines(indent: usize, name: &str, value: &str, x: f64, y: f64, hidden: bool) -> Vec<String> {
    let prefix = " ".repeat(indent);
    let mut lines = vec![
        format!("{prefix}(property {} {}", quote(name), quote(value)),
        format!("{prefix}  (at {} {} 0)", number(x), number(y)),
        format!("{prefix}  (effects"),
        format!("{prefix}    (font (size 1.27 1.27))"),
    ];
    if hidden {
        lines.push(format!("{prefix}    (hide yes)"));
    }
    lines.push(format!("{prefix}  )"));
    lines.push(format!("{prefix})"));
    lines
}

fn wire_lines(board_name: &str, endpoint: &Endpoint, x1: f64, y1: f64, x2: f64, y2: f64) -> Vec<String> {
    let item_uuid = stable_uuid(&[board_name, "wire", &endpoint.to_string()]);
    vec![
        "  (wire".to_owned(),
        format!("    (pts (xy {} {}) (xy {} {}))", number(x1), number(y1), number(x2), number(y2)),
        "    (stroke (width 0) (type default))".to_owned(),
        format!("    (uuid \"{item_uuid}\")"),
        "  )".to_owned(),
    ]
}

fn label_lines(board_name: &str, endpoint: &Endpoint, net_name: &str, x: f64, y: f64, outward: i32) -> Vec<String> {
    let item_uuid = stable_uuid(&[board_name, "label", &endpoint.to_string(), net_name]);
    let (angle, justify) = if outward < 0 { (180, "right bottom") } else { (0, "left bottom") };
    vec![
        format!("  (label {}", quote(net_name)),
        format!("    (at {} {} {angle})", number(x), number(y)),
        "    (fields_autoplaced yes)".to_owned(),
        format!("    (effects (font (size 1.27 1.27)) (justify {justify}))"),
        format!("    (uuid \"{item_uuid}\")"),
        "  )".to_owned(),
    ]
}

fn no_connect_lines(board_name: &str, endpoint: &Endpoint, x: f64, y: f64) -> Vec<String> {
    let item_uuid = stable_uuid(&[board_name, "no-connect", &endpoint.to_string()]);
    vec![
        "  (no_connect".to_owned(),
        format!("    (at {} {})", number(x), number(y)),
        format!("    (uuid \"{item_uuid}\")"),
        "  )".to_owned(),
    ]
}

/// Rows of `COLUMNS` symbols, each row as tall as its tallest symbol.
fn place_components<'a>(
    components: &[&'a ComponentInstance],
    symbols: &IndexMap<&str, PartSymbol<'_>>,
) -> IndexMap<&'a str, (f64, f64)> {
    let step = 190.5 / COLUMNS.saturating_sub(1).max(1) as f64;
    let x_positions: Vec<f64> = (0..COLUMNS).map(|index| 50.8 + index as f64 * step).collect();
    let mut placements = IndexMap::new();
    let mut y_cursor = 25.4;
    for row in components.chunks(COLUMNS) {
        let row_height = row
            .iter()
            .filter_map(|item| symbols.get(item.part.as_str()))
            .map(|symbol| symbol.half_height * 2.0 + 20.32)
            .reduce(f64::max_python)
            .unwrap_or(30.48);
        let y = y_cursor + row_height / 2.0;
        for (index, component) in row.iter().enumerate() {
            placements.insert(component.reference.as_str(), (x_positions[index], y));
        }
        y_cursor += row_height;
    }
    placements
}

/// Python's `max(a, b)`: the first of equal values (the same float here).
trait PythonMax {
    fn max_python(self, other: Self) -> Self;
}

impl PythonMax for f64 {
    fn max_python(self, other: f64) -> f64 {
        if other > self { other } else { self }
    }
}

fn pin_electrical_type(
    part: &PartDefinition,
    pin: &PackagePinDefinition,
    devices: &IndexMap<String, DeviceDefinition>,
) -> &'static str {
    let mut profiles: Vec<&ElectricalProfile> = pin.profile.iter().collect();
    if let Some(device) = devices.get(part.device.as_deref().unwrap_or("")) {
        profiles.extend(pin.bonds.iter().filter_map(|bond| device.pads.get(&bond.pad)).map(|pad| &pad.profile));
    }
    let domains: BTreeSet<SignalDomain> = profiles.iter().flat_map(|profile| profile.domains.iter().copied()).collect();
    let directions: BTreeSet<Direction> =
        profiles.iter().flat_map(|profile| profile.directions.iter().copied()).collect();
    let open_drain = profiles.iter().any(|profile| profile.drive_modes.contains(&DriveMode::OpenDrain));
    let power = domains.contains(&SignalDomain::Power);
    if power && directions.contains(&Direction::Output) {
        "power_out"
    } else if (power || domains.contains(&SignalDomain::Ground)) && directions.contains(&Direction::Input) {
        "power_in"
    } else if directions.contains(&Direction::Bidirectional) {
        "bidirectional"
    } else if open_drain {
        "open_collector"
    } else if directions.contains(&Direction::Output) {
        "output"
    } else if directions.contains(&Direction::Input) {
        "input"
    } else if directions.contains(&Direction::Passive) {
        "passive"
    } else if domains.contains(&SignalDomain::Analog) {
        "bidirectional"
    } else {
        "unspecified"
    }
}

fn component_value(component: &ComponentInstance, part: &PartDefinition) -> String {
    match &component.value {
        None => part.name.rsplit('.').next().unwrap_or(&part.name).to_owned(),
        Some(ComponentValue::Quantity(quantity)) => quantity.to_string(),
        Some(ComponentValue::Text(text)) => text.clone(),
    }
}

fn source_url(part: &PartDefinition) -> &str {
    part.source.as_ref().and_then(|source| source.url.as_deref()).unwrap_or("")
}

fn reference_prefix(part: &PartDefinition) -> &'static str {
    match part.category.as_str() {
        "passive.resistor" => "R",
        "passive.capacitor" => "C",
        "power.source" => "PS",
        _ => "U",
    }
}

fn yes_no(value: bool) -> &'static str {
    if value { "yes" } else { "no" }
}

/// `re.sub(r"[^A-Za-z0-9_]", "_", value)`.
fn identifier_characters(value: &str) -> String {
    value.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect()
}

fn kicad_reference(reference: &str) -> String {
    let safe = identifier_characters(reference);
    if safe.starts_with(|c: char| c.is_ascii_alphabetic()) { safe } else { format!("U_{safe}") }
}

fn safe_name(value: &str) -> String {
    let safe = identifier_characters(value);
    let safe = safe.trim_matches('_');
    if safe.is_empty() { "CopperScript".to_owned() } else { safe.to_owned() }
}

/// A version-4 UUID from the SHA-256 of the seed and the NUL-joined parts.
fn stable_uuid(parts: &[&str]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(UUID_SEED);
    hasher.update(parts.join("\0").as_bytes());
    let mut bytes: [u8; 16] = hasher.finalize()[..16].try_into().expect("16 bytes");
    bytes[6] = (bytes[6] & 0x0F) | 0x40;
    bytes[8] = (bytes[8] & 0x3F) | 0x80;
    let text = hex(&bytes);
    format!("{}-{}-{}-{}-{}", &text[..8], &text[8..12], &text[12..16], &text[16..20], &text[20..])
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

/// A piece of `_pin_sort_key`: digit runs compare as numbers, before text.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
enum SortPiece {
    Number(BigUint),
    Text(String),
}

/// `re.split(r"(\d+)", number)` with digit runs as integers and the rest
/// case-folded. Only ASCII digits form runs and `str.lower` stands for
/// `casefold`, which differ only on characters no pin number uses.
fn pin_sort_key(number: &str) -> Vec<SortPiece> {
    let mut pieces = Vec::new();
    let mut current = String::new();
    let mut digits = false;
    for character in number.chars() {
        if character.is_ascii_digit() != digits && !current.is_empty() {
            pieces.push(sort_piece(digits, std::mem::take(&mut current)));
        }
        digits = character.is_ascii_digit();
        current.push(character);
    }
    if !current.is_empty() {
        pieces.push(sort_piece(digits, current));
    }
    pieces
}

fn sort_piece(digits: bool, piece: String) -> SortPiece {
    if digits { SortPiece::Number(piece.parse().expect("ASCII digits")) } else { SortPiece::Text(piece.to_lowercase()) }
}

/// `(index - (count - 1) / 2) * pitch`.
fn pin_y(index: usize, count: usize) -> f64 {
    (index as f64 - (count as f64 - 1.0) / 2.0) * PITCH
}

/// `f"{value:.4f}"` without trailing zeros, and never `-0`.
fn number(value: f64) -> String {
    let text = format!("{value:.4}");
    let text = text.trim_end_matches('0').trim_end_matches('.');
    if text == "-0" { "0".to_owned() } else { text.to_owned() }
}

/// `json.dumps(value, ensure_ascii=False)`.
fn quote(value: &str) -> String {
    encode_str(value, false)
}

/// `PurePath.suffix` of a file name.
fn suffix(name: &str) -> &str {
    match name.rfind('.') {
        Some(index) if index > 0 && index < name.len() - 1 => &name[index..],
        _ => "",
    }
}

/// `PurePath.with_suffix(new)`.
fn with_suffix(path: &Path, new: &str) -> Result<PathBuf, String> {
    let name = path.file_name().map(|name| name.to_string_lossy().into_owned()).unwrap_or_default();
    if name.is_empty() {
        return Err(format!("{} has an empty name", python_path_repr(path)));
    }
    let stem = &name[..name.len() - suffix(&name).len()];
    Ok(path.with_file_name(format!("{stem}{new}")))
}

fn python_path_repr(path: &Path) -> String {
    let class = if cfg!(windows) { "WindowsPath" } else { "PosixPath" };
    format!("{class}({})", copper_json::python_str_repr(&paths::display(path)))
}

/// `write_kicad_schematic(manifest, output)`: the schematic at `output`,
/// the library and table beside it, the project at `output` with suffix
/// `.kicad_pro` unless one exists. An error is the `OSError` or
/// `ValueError` text Python prints after `OUTPUT ERROR: `.
pub fn write_schematic(manifest: &SchematicManifest, output: &Path) -> Result<Vec<PathBuf>, String> {
    let os_error = |error: std::io::Error, path: &Path| paths::python_os_error(&error, Some(&paths::display(path)));
    let parent = match output.parent() {
        Some(parent) if !parent.as_os_str().is_empty() => parent.to_path_buf(),
        _ => PathBuf::from("."),
    };
    let root = paths::resolve(&parent);
    let mut destinations = Vec::with_capacity(manifest.artifacts.len());
    for (index, artifact) in manifest.artifacts.iter().enumerate() {
        let path = match index {
            0 => output.to_path_buf(),
            3 => with_suffix(output, ".kicad_pro")?,
            _ => root.join(&artifact.name),
        };
        if !paths::is_relative_to(&paths::resolve(&path), &root) {
            return Err(format!("artifact escapes output directory: {}", copper_json::python_str_repr(&artifact.name)));
        }
        destinations.push(path);
    }
    let unique: BTreeSet<String> =
        destinations.iter().map(|path| paths::display(&paths::resolve(path)).to_lowercase()).collect();
    if unique.len() != destinations.len() {
        return Err("generated artifact destinations collide".to_owned());
    }
    for (artifact, path) in manifest.artifacts[1..3].iter().zip(&destinations[1..3]) {
        if path.exists() {
            let existing = std::fs::read(path).map_err(|error| os_error(error, path))?;
            if existing != artifact.content.as_bytes() {
                let name = path.file_name().map(|name| name.to_string_lossy().into_owned()).unwrap_or_default();
                return Err(format!("refusing to overwrite unrelated {name}; export to a separate build directory"));
            }
        }
    }
    for (artifact, path) in manifest.artifacts.iter().zip(&destinations) {
        let name = path.file_name().map(|name| name.to_string_lossy().into_owned()).unwrap_or_default();
        let project = suffix(&name) == ".kicad_pro";
        if project && path.exists() {
            continue; // Preserve an existing PCB project's rules and settings.
        }
        if let Some(directory) = path.parent().filter(|directory| !directory.as_os_str().is_empty()) {
            std::fs::create_dir_all(directory)
                .map_err(|error| paths::python_os_call_error(&error, Some(&paths::display(directory))))?;
        }
        let content = if project { project_json(&name) } else { artifact.content.clone() };
        std::fs::write(path, content.as_bytes()).map_err(|error| os_error(error, path))?;
    }
    Ok(destinations)
}

