/// `_mm`: exact fixed-point millimetres.
pub fn mm(value_nm: i64) -> String {
    let sign = if value_nm < 0 { "-" } else { "" };
    let magnitude = value_nm.unsigned_abs();
    let (whole, fractional) = (magnitude / 1_000_000, magnitude % 1_000_000);
    if fractional == 0 {
        return format!("{sign}{whole}");
    }
    let text = format!("{sign}{whole}.{fractional:06}");
    text.trim_end_matches('0').to_owned()
}

fn area_mm2(value_nm2: i64) -> String {
    let (whole, fractional) = (value_nm2.div_euclid(1_000_000_000_000), value_nm2.rem_euclid(1_000_000_000_000));
    if fractional == 0 {
        return whole.to_string();
    }
    format!("{whole}.{fractional:012}").trim_end_matches('0').to_owned()
}

fn ratio(value_ppm: i64) -> String {
    let (whole, fractional) = (value_ppm.div_euclid(1_000_000), value_ppm.rem_euclid(1_000_000));
    if fractional == 0 {
        return whole.to_string();
    }
    format!("{whole}.{fractional:06}").trim_end_matches('0').to_owned()
}

/// `_decimal`: `format(value, "f")` without trailing zeros (keeping `-0`).
fn decimal(value: &Decimal) -> String {
    let mut text = value.to_fixed_string();
    if text.contains('.') {
        let trimmed = text.trim_end_matches('0').trim_end_matches('.').len();
        text.truncate(trimmed);
    }
    if text.is_empty() { "0".to_owned() } else { text }
}

fn decimal_text(value: &Decimal) -> String {
    value.normalize().map(|v| v.to_fixed_string()).unwrap_or_else(|_| value.to_fixed_string())
}

fn quote(value: &str) -> String {
    encode_str(value, false)
}

/// `_safe_name`.
pub fn safe_name(value: &str) -> String {
    let replaced: String = value.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    let stripped = replaced.trim_matches('_');
    if stripped.is_empty() { "CopperScript".to_owned() } else { stripped.to_owned() }
}

/// `kicad_reference`: a deterministic backend reference.
pub fn kicad_reference(value: &str) -> String {
    let safe: String = value.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    if safe.chars().next().is_some_and(|c| c.is_alphabetic()) { safe } else { format!("U_{safe}") }
}

/// `_stable_uuid`: a version-4 UUID from the namespaced parts.
fn stable_uuid(parts: &[&str]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(UUID_SEED);
    hasher.update(parts.join("\0").as_bytes());
    let mut bytes: Vec<u8> = hasher.finalize()[..16].to_vec();
    bytes[6] = (bytes[6] & 0x0F) | 0x40;
    bytes[8] = (bytes[8] & 0x3F) | 0x80;
    let hex: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
    format!("{}-{}-{}-{}-{}", &hex[..8], &hex[8..12], &hex[12..16], &hex[16..20], &hex[20..])
}

fn point(point: Point) -> String {
    format!("{} {}", mm(point.x_nm), mm(point.y_nm))
}

fn placement_rotation(placement: &Placement) -> Decimal {
    let extra = if placement.side == BoardSide::Back { 180 } else { 0 };
    let sum = placement.rotation_degrees.add(&Decimal::from_i64(extra)).expect("finite rotation");
    crate::decimal_rem(&sum, 360).expect("finite rotation")
}

fn courtyard_gap(board: &PhysicalBoard, first: &str, second: &str) -> i64 {
    let explicit = |reference: &str| {
        board.placement_rules.iter().find(|r| r.reference == reference).and_then(|r| r.additional_courtyard_gap_nm)
    };
    let mut internal: Option<i64> = None;
    for cluster in &board.rigid_clusters {
        let Some(clearance) = cluster.internal_clearance_nm else { continue };
        let members: Vec<&str> = cluster.members.iter().map(|m| m.reference.as_str()).collect();
        if members.contains(&first) && members.contains(&second) {
            internal = Some(internal.unwrap_or(0).max(clearance));
        }
    }
    let (a, b) = (explicit(first), explicit(second));
    match internal {
        Some(gap) => gap.max(a.unwrap_or(0)).max(b.unwrap_or(0)),
        None => a.unwrap_or(DEFAULT_ADDITIONAL_COURTYARD_GAP_NM).max(b.unwrap_or(DEFAULT_ADDITIONAL_COURTYARD_GAP_NM)),
    }
}

/// `_courtyard_pair_groups`: nondefault courtyard gaps as compact bicliques.
/// A nondefault courtyard gap between two groups of references.
type PairGroup = (i64, Vec<String>, Vec<String>);

fn courtyard_pair_groups(board: &PhysicalBoard) -> Result<Vec<PairGroup>> {
    let mut references: Vec<&str> = board.placements.iter().map(|p| p.reference.as_str()).collect();
    references.sort_unstable();
    let exported: Vec<String> = references.iter().map(|r| kicad_reference(r)).collect();
    if crate::has_duplicates(&exported) {
        return fail("cannot export courtyard gaps with colliding native references");
    }
    let mut graphs: std::collections::BTreeMap<
        i64,
        std::collections::BTreeMap<String, std::collections::BTreeSet<String>>,
    > = std::collections::BTreeMap::new();
    for (i, first) in references.iter().enumerate() {
        for second in &references[i + 1..] {
            let gap = courtyard_gap(board, first, second);
            if gap == DEFAULT_ADDITIONAL_COURTYARD_GAP_NM {
                continue;
            }
            let graph = graphs.entry(gap).or_default();
            graph.entry((*first).to_owned()).or_default().insert((*second).to_owned());
            graph.entry((*second).to_owned()).or_default().insert((*first).to_owned());
        }
    }
    let mut result = Vec::new();
    for (gap, graph) in graphs {
        let mut groups: std::collections::BTreeMap<Vec<String>, Vec<String>> = std::collections::BTreeMap::new();
        for (reference, neighbours) in &graph {
            let mut key: Vec<String> = neighbours.iter().cloned().collect();
            key.push(reference.clone());
            key.sort();
            key.dedup();
            groups.entry(key).or_default().push(reference.clone());
        }
        for (neighbours, left) in groups {
            result.push((gap, left, neighbours));
        }
    }
    Ok(result)
}

fn courtyard_rules(board: &PhysicalBoard) -> Result<Vec<String>> {
    let mut lines = vec![
        "# Additional courtyard gaps are source member floors; rigid interiors keep their audited contract.".to_owned(),
        "# Nonnegative minima never waive actual courtyard interior overlap; zero means exact zero extra gap."
            .to_owned(),
        "(rule \"Default additional courtyard gap\"".to_owned(),
        format!("  (constraint courtyard_clearance (min {}mm)))", mm(DEFAULT_ADDITIONAL_COURTYARD_GAP_NM)),
    ];
    let membership = |side: &str, refs: &[String]| {
        let terms: Vec<String> = refs.iter().map(|r| format!("{side}.Reference == '{}'", kicad_reference(r))).collect();
        format!("({})", terms.join(" || "))
    };
    for (index, (gap, left, right)) in courtyard_pair_groups(board)?.iter().enumerate() {
        let condition = format!("{} && {}", membership("A", left), membership("B", right));
        lines.push(format!("(rule \"Source additional courtyard gap {}\"", index + 1));
        lines.push(format!("  (constraint courtyard_clearance (min {}mm))", mm(*gap)));
        lines.push(format!("  (condition {}))", quote(&condition)));
    }
    Ok(lines)
}

/// `routing_clearance_rules`: source net clearances, stricter rules last.
fn routing_clearance_rules(board: &PhysicalBoard) -> Vec<String> {
    let mut values: Vec<(i64, &str)> = Vec::new();
    for rule in &board.net_routing_rules {
        let Some(mut clearance) = rule.clearance_nm else { continue };
        if let Some(breakout) = rule.breakout_clearance_nm {
            clearance = clearance.min(breakout);
        }
        clearance = clearance.max(board.rules.minimum_clearance_nm);
        if clearance > board.rules.minimum_clearance_nm {
            values.push((clearance, rule.net.as_str()));
        }
    }
    values.sort();
    let mut lines = Vec::new();
    for (clearance, net) in values {
        let literal = net.replace('\\', "\\\\").replace('\'', "\\'");
        let condition = format!("A.NetName == '{literal}' || B.NetName == '{literal}'");
        let millimetres =
            Decimal::from_i64(clearance).div(&Decimal::from_i64(1_000_000)).expect("finite").to_fixed_string();
        lines.push(format!("(rule {}", encode_str(&format!("CopperScript clearance {net}"), true)));
        lines.push(format!("  (constraint clearance (min {millimetres}mm))"));
        lines.push(format!("  (condition {}))", encode_str(&condition, true)));
    }
    lines
}

fn render_rules(board: &PhysicalBoard) -> Result<String> {
    let exported: Vec<String> = board.placements.iter().map(|p| kicad_reference(&p.reference)).collect();
    let mut lines = vec!["(version 1)".to_owned(), KICAD_RULES_MARKER.to_owned()];
    lines.extend(courtyard_rules(board)?);
    let mut clearances: Vec<&ComponentHoleClearance> = board.component_hole_clearances.iter().collect();
    clearances.sort_by(|a, b| a.reference.cmp(&b.reference));
    for rule in clearances {
        let reference = kicad_reference(&rule.reference);
        if exported.iter().filter(|r| **r == reference).count() != 1 {
            return Err(Error::Value(format!(
                "cannot export hole_clearance for {}: KiCad reference {} is not unique on the board",
                copper_json::python_str_repr(&rule.reference),
                copper_json::python_str_repr(&reference)
            )));
        }
        let member = format!("memberOfFootprint('{reference}')");
        let reason: Vec<&str> = rule.reason.split_whitespace().collect();
        lines.push(format!("# {}: {}", rule.reference, reason.join(" ")));
        lines.push(format!("(rule {}", quote(&format!("{reference} hole clearance"))));
        lines.push(format!("  (constraint hole_clearance (min {}mm))", mm(rule.clearance_nm)));
        lines.push(format!(
            "  (condition \"A.{member} && B.{member} && (A.Pad_Type == 'NPTH, mechanical' || B.Pad_Type == 'NPTH, mechanical')\"))"
        ));
    }
    lines.extend(routing_clearance_rules(board));
    Ok(lines.join("\n") + "\n")
}

fn uses_internal_connections(board: &PhysicalBoard) -> bool {
    board.placements.iter().any(|p| !board.footprints[&p.footprint].internal_pad_groups.is_empty())
}

fn json_float(value: f64) -> Json {
    Json::Float(value)
}

/// `_render_project`: board-wide DRC rules pinned to the physical IR.
fn render_project(board: &PhysicalBoard) -> String {
    let rules = &board.rules;
    let f = |nm: i64| nm as f64 / 1_000_000.0;
    let clearance = f(rules.minimum_clearance_nm);
    let hole_clearance = f(rules.minimum_hole_clearance_nm);
    let filled_capped = board.vias.iter().any(|v| v.finish == "filled-capped");
    let mut sizes = vec![(rules.default_via_size_nm, rules.default_via_drill_nm)];
    sizes.extend(board.vias.iter().filter(|v| v.finish != "filled-capped").map(|v| (v.size_nm, v.drill_nm)));
    let mut design: Object = Object::new();
    design.insert("min_clearance".to_owned(), json_float(clearance));
    design.insert("min_copper_edge_clearance".to_owned(), json_float(clearance));
    design.insert("min_hole_clearance".to_owned(), json_float(hole_clearance));
    design.insert("min_hole_to_hole".to_owned(), json_float(hole_clearance));
    design.insert("min_track_width".to_owned(), json_float(f(rules.minimum_track_width_nm)));
    if filled_capped {
        design.insert("min_via_diameter".to_owned(), json_float(0.30));
        design.insert("min_through_hole_diameter".to_owned(), json_float(0.20));
        design.insert("min_via_annular_width".to_owned(), json_float(0.05));
    } else {
        let min_size = sizes.iter().map(|s| s.0).min().unwrap();
        let min_drill = sizes.iter().map(|s| s.1).min().unwrap();
        let min_annular = sizes.iter().map(|(s, d)| (s - d) as f64 / 2.0).fold(f64::INFINITY, f64::min);
        design.insert("min_via_diameter".to_owned(), json_float(f(min_size)));
        design.insert("min_through_hole_diameter".to_owned(), json_float(f(min_drill)));
        design.insert("min_via_annular_width".to_owned(), json_float(min_annular / 1_000_000.0));
        if let Some(size) = rules.minimum_via_size_nm {
            design.insert("min_via_diameter".to_owned(), json_float(f(size)));
        }
        if let Some(drill) = rules.minimum_via_drill_nm {
            design.insert("min_through_hole_diameter".to_owned(), json_float(f(drill)));
        }
    }
    let object =
        |entries: Vec<(&str, Json)>| Json::Object(entries.into_iter().map(|(k, v)| (k.to_owned(), v)).collect());
    let class = object(vec![
        ("name", Json::from("Default")),
        ("priority", Json::from(2_147_483_647i64)),
        ("clearance", json_float(clearance)),
        ("track_width", json_float(f(rules.default_track_width_nm))),
        ("via_diameter", json_float(f(rules.default_via_size_nm))),
        ("via_drill", json_float(f(rules.default_via_drill_nm))),
    ]);
    let project = object(vec![
        (
            "meta",
            object(vec![
                ("filename", Json::from(format!("{}.kicad_pro", safe_name(&board.name)).as_str())),
                ("version", Json::from(3i64)),
            ]),
        ),
        ("board", object(vec![("design_settings", object(vec![("rules", Json::Object(design))]))])),
        (
            "net_settings",
            object(vec![
                ("classes", Json::Array(vec![class])),
                ("meta", object(vec![("version", Json::from(4i64))])),
                ("net_colors", Json::Null),
                ("netclass_assignments", Json::Null),
                ("netclass_patterns", Json::Array(Vec::new())),
            ]),
        ),
    ]);
    Dumps::new().indent(2).sort_keys(true).dumps(&project) + "\n"
}

/// `_render_via_process`: fabrication intent the native board does not represent.
fn render_via_process(board: &PhysicalBoard) -> String {
    let mut vias: Vec<&Via> = board.vias.iter().filter(|v| v.finish != "standard").collect();
    vias.sort_by(|a, b| {
        let key = |v: &Via| {
            (
                v.net.clone(),
                v.position.x_nm,
                v.position.y_nm,
                v.from_layer.value(),
                v.to_layer.value(),
                v.size_nm,
                v.drill_nm,
                v.finish.clone(),
            )
        };
        key(a).cmp(&key(b))
    });
    let object =
        |entries: Vec<(&str, Json)>| Json::Object(entries.into_iter().map(|(k, v)| (k.to_owned(), v)).collect());
    let rows = vias
        .iter()
        .map(|via| {
            object(vec![
                ("net", Json::from(via.net.as_str())),
                ("position_nm", Json::Array(vec![Json::from(via.position.x_nm), Json::from(via.position.y_nm)])),
                ("diameter_nm", Json::from(via.size_nm)),
                ("drill_nm", Json::from(via.drill_nm)),
                ("layers", Json::Array(vec![Json::from(via.from_layer.value()), Json::from(via.to_layer.value())])),
                ("finish", Json::from(via.finish.as_str())),
                ("technology", via.technology.as_deref().map_or(Json::Null, Json::from)),
            ])
        })
        .collect();
    let document = object(vec![
        ("schema", Json::from("copperscript-via-process/v0.1")),
        ("generated_by", Json::from("CopperScript")),
        (
            "fabrication_profile",
            board.metadata.get("fabrication_profile").map_or(Json::Null, |p| Json::from(p.as_str())),
        ),
        ("fabrication_ready", Json::Bool(false)),
        ("vias", Json::Array(rows)),
    ]);
    Dumps::new().indent(2).sort_keys(true).dumps(&document) + "\n"
}

fn library_item_name(footprint: &PhysicalFootprint) -> String {
    let leaf = footprint.name.rsplit(':').next().unwrap_or(&footprint.name).replace('\\', "/");
    let leaf = leaf.rsplit('/').next().unwrap_or(&leaf).to_owned();
    let safe: String = safe_name(&leaf).chars().take(64).collect();
    format!("{safe}__{}", &footprint_geometry_digest(footprint)[..20])
}

fn render_library_table() -> String {
    format!(
        "(fp_lib_table\n  (version 7)\n  (lib (name \"{GENERATED_LIBRARY}\")(type \"KiCad\")(uri \"${{KIPRJMOD}}/{GENERATED_LIBRARY_DIRECTORY}\")(options \"\")(descr \"Generated by CopperScript; do not edit\"))\n)\n"
    )
}

fn render_library_footprint(board: &PhysicalBoard, footprint: &PhysicalFootprint, name: &str) -> Result<String> {
    let mut pose = Placement::new("REF", &footprint.name, Point::new(0, 0), &Decimal::zero())?;
    pose.value = name.to_owned();
    let mut lines = footprint_lines(
        board,
        &pose,
        footprint,
        &IndexMap::new(),
        &IndexMap::new(),
        name,
        &format!("{GENERATED_LIBRARY}:{name}"),
        true,
    );
    let version = if footprint.internal_pad_groups.is_empty() { KICAD_PCB_FORMAT } else { "20260206" };
    lines.splice(1..1, [format!("    (version {version})"), "    (generator \"copperscript\")".to_owned()]);
    Ok(lines.join("\n") + "\n")
}

/// `_mechanical_export_board`: board-owned holes and slots as NPTH footprints.
fn mechanical_export_board(board: &PhysicalBoard) -> Result<PhysicalBoard> {
    if board.mechanical_holes.is_empty() && board.mechanical_slots.is_empty() {
        return Ok(board.clone());
    }
    let mut out = board.clone();
    let hex = |text: &str| -> String {
        Sha256::digest(text.as_bytes()).iter().map(|b| format!("{b:02x}")).collect::<String>()[..16].to_owned()
    };
    let npth = |size: Size, shape: PadShape| FootprintPad {
        number: String::new(),
        position: Point::new(0, 0),
        size,
        kind: PadKind::NonPlatedThroughHole,
        shape,
        rotation_degrees: Decimal::zero(),
        drill: Some(size),
        roundrect_ratio_ppm: 250_000,
        has_solder_mask: true,
        has_solder_paste: false,
        zone_connection: None,
        heatsink: false,
        remove_unused_layers: false,
        connector_contact: false,
    };
    let base = |name: String, pad: FootprintPad, size: Size, graphic: FootprintGraphic| PhysicalFootprint {
        name,
        pads: vec![pad],
        body_size: size,
        source_library_id: None,
        graphics: vec![graphic],
        keepouts: Vec::new(),
        metadata: IndexMap::new(),
        courtyard: Vec::new(),
        height_nm: None,
        clearance_nm: None,
        exclude_from_bom: true,
        exclude_from_pos_files: true,
        internal_pad_groups: Vec::new(),
    };
    let mut holes = board.mechanical_holes.clone();
    holes.sort_by(|a, b| a.id.cmp(&b.id));
    for hole in holes {
        let reference = format!("CS_MH_{}", hex(&hole.id));
        let name = format!("__mechanical_hole_{}", hole.diameter_nm);
        if out.placements.iter().any(|p| p.reference == reference) {
            return fail("generated mechanical hole reference conflicts with a component");
        }
        let size = Size::new(hole.diameter_nm, hole.diameter_nm)?;
        let graphic = FootprintGraphic::Circle {
            center: Point::new(0, 0),
            end: Point::new((hole.diameter_nm + 1) / 2, 0),
            width_nm: 50_000,
            layer: FootprintLayer::Fabrication,
            filled: false,
        };
        let footprint = base(name.clone(), npth(size, PadShape::Circle), size, graphic);
        if out.footprints.get(&name).is_some_and(|existing| *existing != footprint) {
            return fail("generated mechanical hole asset conflicts with a footprint");
        }
        out.footprints.insert(name.clone(), footprint);
        let mut placement = Placement::new(&reference, &name, hole.position, &Decimal::zero())?;
        placement.source_path = Some(format!("mechanical:{}", hole.id));
        out.placements.push(placement);
    }
    let mut slots = board.mechanical_slots.clone();
    slots.sort_by(|a, b| a.id.cmp(&b.id));
    for slot in slots {
        let reference = format!("CS_MS_{}", hex(&slot.id));
        if out.placements.iter().any(|p| p.reference == reference) {
            return fail("generated slot reference conflicts with a component");
        }
        let (dx, dy) = ((slot.end.x_nm - slot.start.x_nm) as f64, (slot.end.y_nm - slot.start.y_nm) as f64);
        let length = copper_physical::pyfloat::round_int(dx.hypot(dy));
        let size = Size::new(length + slot.width_nm, slot.width_nm)?;
        let name = format!("__mechanical_slot_{}_{}", size.width_nm, size.height_nm);
        let graphic = FootprintGraphic::Rectangle {
            start: Point::new((-size.width_nm).div_euclid(2), (-size.height_nm).div_euclid(2)),
            end: Point::new(size.width_nm / 2, size.height_nm / 2),
            width_nm: 50_000,
            layer: FootprintLayer::Fabrication,
            filled: false,
        };
        let footprint = base(name.clone(), npth(size, PadShape::Oval), size, graphic);
        if out.footprints.get(&name).is_some_and(|existing| *existing != footprint) {
            return fail("generated slot asset conflicts with a footprint");
        }
        out.footprints.insert(name.clone(), footprint);
        let origin = Point::new(
            copper_physical::pyfloat::round_int((slot.start.x_nm + slot.end.x_nm) as f64 / 2.0),
            copper_physical::pyfloat::round_int((slot.start.y_nm + slot.end.y_nm) as f64 / 2.0),
        );
        let rotation = crate::float_decimal(-dy.atan2(dx).to_degrees())?;
        let mut placement = Placement::new(&reference, &name, origin, &rotation)?;
        placement.source_path = Some(format!("mechanical:{}", slot.id));
        out.placements.push(placement);
    }
    out.mechanical_holes.clear();
    out.mechanical_slots.clear();
    Ok(out)
}

/// `KiCadPcbBackend.generate`.
pub fn generate(board: &PhysicalBoard) -> Result<Manifest> {
    let has_head_clearance = board.mechanical_holes.iter().any(|h| h.head_clearance_radius_nm != 0);
    let board = mechanical_export_board(board)?;
    if board.stackup.copper_layers.first() != Some(&CopperLayer::Front)
        || board.stackup.copper_layers.last() != Some(&CopperLayer::Back)
    {
        return fail("KiCad stackups must start at F.Cu and end at B.Cu");
    }
    let mut references: Vec<&str> = board.placements.iter().map(|p| p.footprint.as_str()).collect();
    references.sort_unstable();
    references.dedup();
    let names: IndexMap<String, String> =
        references.iter().map(|r| ((*r).to_owned(), library_item_name(&board.footprints[*r]))).collect();
    let folded: Vec<String> = names.values().map(|n| n.to_lowercase()).collect();
    if crate::has_duplicates(&folded) {
        return fail("generated footprint names collide");
    }
    let content = render(&board, &names)?;
    let mut warnings: Vec<String> = Vec::new();
    if has_head_clearance {
        warnings.push("Screw-head clearance is enforced by CopperScript placement, not exported as a native KiCad placement constraint; recheck after manual placement changes.".to_owned());
    }
    if !board.hard_macros.is_empty() {
        let owners: indexmap::IndexSet<&str> = board.hard_macros.iter().map(|m| m.cluster.as_str()).collect();
        let materialized: indexmap::IndexSet<&str> = board.materialized_macros.iter().map(String::as_str).collect();
        if owners != materialized {
            return fail("cannot export a hard macro without its immutable copper");
        }
        warnings.push("Experimental physical hard macros are not RF or manufacturing qualification.".to_owned());
        if board.hard_macros.iter().any(|m| m.width_contracts > 0) {
            warnings.push(
                "Scoped macro widths require authoritative CopperScript owner validation; native KiCad edits do not preserve these contracts or qualify current capacity."
                    .to_owned(),
            );
        }
    }
    if board.metadata.get("prototype_footprints").map(String::as_str) == Some("true") {
        warnings.push("The board uses generated proxy footprints and is for inspection only; resolve verified package footprints before fabrication.".to_owned());
    }
    if board.metadata.get("prototype_placement").map(String::as_str) == Some("true") {
        warnings.push(
            "Components use deterministic draft placement; review and constrain placement before fabrication."
                .to_owned(),
        );
    }
    if let Some(import) = board.metadata.get("footprint_import_warnings")
        && !import.is_empty()
    {
        warnings.extend(import.lines().map(str::to_owned));
    }
    if board.tracks.is_empty() {
        warnings.push("The board contains no routed tracks.".to_owned());
    }
    let mut via_process = None;
    if board.vias.iter().any(|v| v.finish != "standard") {
        via_process =
            Some(artifact(format!("{}.via-process.json", safe_name(&board.name)), render_via_process(&board)));
        warnings.push(
            "Non-standard via finishes are recorded in the .via-process.json sidecar; keep it with the project. The native PCB alone does not encode this process and the sidecar is not manufacturing qualification."
                .to_owned(),
        );
    }
    let clearance_rules = routing_clearance_rules(&board);
    let mut rules = None;
    if !board.component_hole_clearances.is_empty() || board.placements.len() > 1 || !clearance_rules.is_empty() {
        rules = Some(artifact(format!("{}.kicad_dru", safe_name(&board.name)), render_rules(&board)?));
        if !board.component_hole_clearances.is_empty() {
            let mut sorted: Vec<&ComponentHoleClearance> = board.component_hole_clearances.iter().collect();
            sorted.sort_by(|a, b| a.reference.cmp(&b.reference));
            let listed: Vec<String> =
                sorted.iter().map(|r| format!("{}: {} mm", r.reference, mm(r.clearance_nm))).collect();
            warnings.push(format!(
                "Component-scoped hole clearances ({}) are KiCad custom rules in the .kicad_dru; keep it beside the project.",
                listed.join(", ")
            ));
        }
        if !clearance_rules.is_empty() {
            warnings.push("Source net clearances are KiCad custom rules in the .kicad_dru; keep it beside the project for native DRC and zone refill.".to_owned());
        }
        if board.net_routing_rules.iter().any(|r| r.clearance_nm.is_some() && r.breakout_clearance_nm.is_some()) {
            warnings.push("Native net clearance exports the breakout lower bound, not its region; CopperScript must recheck nominal/escape clearance ownership.".to_owned());
        }
    }
    let mut artifacts = vec![
        artifact(format!("{}.kicad_pcb", safe_name(&board.name)), content),
        artifact(format!("{}.kicad_pro", safe_name(&board.name)), render_project(&board)),
    ];
    let early = !board.component_hole_clearances.is_empty();
    if early && let Some(rules) = &rules {
        artifacts.push(rules.clone());
    }
    artifacts.extend(via_process);
    artifacts.push(artifact("fp-lib-table".to_owned(), render_library_table()));
    for (reference, name) in &names {
        artifacts.push(artifact(
            format!("{GENERATED_LIBRARY_DIRECTORY}/{name}.kicad_mod"),
            render_library_footprint(&board, &board.footprints[reference], name)?,
        ));
    }
    if !early && let Some(rules) = rules {
        artifacts.push(rules);
    }
    let target =
        if uses_internal_connections(&board) || !board.polygons.is_empty() { "10.0" } else { KICAD_PCB_TARGET_VERSION };
    Ok(Manifest { target_version: target.to_owned(), artifacts, warnings })
}

fn copper_layer_lines(board: &PhysicalBoard) -> Vec<String> {
    board
        .stackup
        .copper_layers
        .iter()
        .map(|layer| {
            let number = match layer {
                CopperLayer::Front => 0,
                CopperLayer::Back => 31,
                other => other.value()[2..other.value().len() - 3].parse().unwrap_or(0),
            };
            format!("    ({number} \"{}\" signal)", layer.value())
        })
        .collect()
}

fn stackup_lines(board: &PhysicalBoard) -> Vec<String> {
    let layers = &board.stackup.physical_layers;
    if layers.is_empty() {
        return Vec::new();
    }
    let mut result = vec!["    (stackup".to_owned()];
    let mut dielectric = 0;
    for layer in layers {
        if let Some(copper) = layer.copper_layer {
            result.push(format!(
                "      (layer {} (type \"copper\") (thickness {}))",
                quote(copper.value()),
                mm(layer.thickness_nm)
            ));
            continue;
        }
        dielectric += 1;
        let construction = layer.dielectric_type.clone().unwrap_or_else(|| {
            if board.stackup.copper_layers.len() == 2 || dielectric % 2 == 0 { "core" } else { "prepreg" }.to_owned()
        });
        let mut attributes =
            vec![format!("(type {})", quote(&construction)), format!("(thickness {})", mm(layer.thickness_nm))];
        if let Some(material) = &layer.material {
            attributes.push(format!("(material {})", quote(material)));
        }
        if let Some(value) = &layer.relative_permittivity {
            attributes.push(format!("(epsilon_r {})", decimal_text(value)));
        }
        if let Some(value) = &layer.loss_tangent {
            attributes.push(format!("(loss_tangent {})", decimal_text(value)));
        }
        result.push(format!("      (layer \"dielectric {dielectric}\" {})", attributes.join(" ")));
    }
    result.extend([
        "      (copper_finish \"None\")".to_owned(),
        "      (dielectric_constraints no)".to_owned(),
        "    )".to_owned(),
    ]);
    result
}

fn zone_lines(
    board: &PhysicalBoard,
    zone: &CopperZone,
    layer: CopperLayer,
    net_codes: &IndexMap<String, usize>,
    locked: bool,
) -> Result<Vec<String>> {
    if !zone.holes.is_empty() {
        return Err(Error::Value(format!(
            "KiCad zone backend does not yet support holes in zone {}; use an explicit copper keepout",
            copper_json::python_str_repr(&zone.id)
        )));
    }
    let connection = match zone.pad_connection {
        ZoneConnection::Thermal => "",
        ZoneConnection::Solid => " yes",
        ZoneConnection::None => " no",
        ZoneConnection::ThtThermal => " thru_hole_only",
    };
    let clearance = zone.clearance_nm.unwrap_or(board.rules.minimum_clearance_nm);
    let island = match zone.island_policy {
        IslandPolicy::RemoveAll => 0,
        IslandPolicy::KeepAll => 1,
        IslandPolicy::RemoveBelowArea => 2,
    };
    let mut fill = format!(
        "    (fill yes (thermal_gap {}) (thermal_bridge_width {}) (island_removal_mode {island})",
        mm(zone.thermal_gap_nm),
        mm(zone.thermal_spoke_width_nm)
    );
    if zone.island_policy == IslandPolicy::RemoveBelowArea {
        fill += &format!(" (island_area_min {})", area_mm2(zone.minimum_island_area_nm2.unwrap_or(0)));
    }
    fill += ")";
    let mut result = vec!["  (zone".to_owned()];
    if locked {
        result.push("    (locked yes)".to_owned());
    }
    result.extend([
        format!("    (net {})", net_codes[&zone.net]),
        format!("    (net_name {})", quote(&zone.net)),
        format!("    (layer {})", quote(layer.value())),
        format!("    (uuid \"{}\")", stable_uuid(&[&board.name, "zone", &zone.id, layer.value()])),
        format!("    (name {})", quote(&zone.id)),
        "    (hatch edge 0.5)".to_owned(),
    ]);
    if zone.priority != 0 {
        result.push(format!("    (priority {})", zone.priority));
    }
    result.push(format!("    (connect_pads{connection} (clearance {}))", mm(clearance)));
    result.push(format!("    (min_thickness {})", mm(zone.minimum_width_nm)));
    result.push(fill);
    result.push("    (polygon".to_owned());
    result.push("      (pts".to_owned());
    result.extend(zone.outer.iter().map(|p| format!("        (xy {})", point(*p))));
    result.extend(["      )".to_owned(), "    )".to_owned(), "  )".to_owned()]);
    Ok(result)
}

fn copper_keepout_lines(
    board_name: &str,
    keepout: &CopperKeepout,
    vertices: &[Point],
    layer: CopperLayer,
    identity: &str,
    footprint_local: bool,
) -> Vec<String> {
    let setting = |blocked: bool| if blocked { "not_allowed" } else { "allowed" };
    let lines = vec![
        "  (zone".to_owned(),
        "    (net 0)".to_owned(),
        "    (net_name \"\")".to_owned(),
        format!("    (layer {})", quote(layer.value())),
        format!("    (uuid \"{}\")", stable_uuid(&[board_name, "copper-keepout", identity, layer.value()])),
        format!("    (name {})", quote(if footprint_local { &keepout.id } else { identity })),
        "    (hatch edge 0.5)".to_owned(),
        "    (keepout".to_owned(),
        format!("      (tracks {})", setting(keepout.block_tracks)),
        format!("      (vias {})", setting(keepout.block_vias)),
        format!("      (pads {})", setting(keepout.block_pads)),
        format!("      (copperpour {})", setting(keepout.block_zones)),
        format!("      (footprints {})", setting(keepout.block_footprints)),
        "    )".to_owned(),
        "    (polygon".to_owned(),
        "      (pts".to_owned(),
    ];
    let mut lines = lines;
    lines.extend(vertices.iter().map(|p| format!("        (xy {})", point(*p))));
    lines.extend(["      )".to_owned(), "    )".to_owned(), "  )".to_owned()]);
    if footprint_local { lines.into_iter().map(|line| format!("  {line}")).collect() } else { lines }
}

#[allow(clippy::too_many_arguments)]
fn property_lines(
    board_name: &str,
    reference: &str,
    name: &str,
    value: &str,
    x_nm: i64,
    y_nm: i64,
    layer: &str,
    hidden: bool,
) -> Vec<String> {
    let mut lines = vec![
        format!("    (property {} {}", quote(name), quote(value)),
        format!("      (at {} {} 0)", mm(x_nm), mm(y_nm)),
        format!("      (layer {})", quote(layer)),
    ];
    if hidden {
        lines.push("      (hide yes)".to_owned());
    }
    lines.push(format!("      (uuid \"{}\")", stable_uuid(&[board_name, "property", reference, name])));
    lines.push(format!(
        "      (effects (font (size 1 1) (thickness 0.15)){})",
        if layer.starts_with("B.") { " (justify mirror)" } else { "" }
    ));
    lines.push("    )".to_owned());
    lines
}

fn footprint_layer(layer: FootprintLayer, side: BoardSide) -> String {
    let prefix = if side == BoardSide::Front { "F" } else { "B" };
    match layer {
        FootprintLayer::Silkscreen => format!("{prefix}.SilkS"),
        FootprintLayer::Fabrication => format!("{prefix}.Fab"),
        FootprintLayer::Courtyard => format!("{prefix}.CrtYd"),
        FootprintLayer::Adhesive => format!("{prefix}.Adhes"),
        FootprintLayer::Documentation => "Dwgs.User".to_owned(),
        FootprintLayer::SolderMask => format!("{prefix}.Mask"),
        FootprintLayer::SolderPaste => format!("{prefix}.Paste"),
    }
}

fn graphic_lines(board_name: &str, placement: &Placement, graphic: &FootprintGraphic, index: usize) -> Vec<String> {
    let back = placement.side == BoardSide::Back;
    let m = |p: &Point| if back { Point::new(p.x_nm, -p.y_nm) } else { *p };
    let class = match graphic {
        FootprintGraphic::Line { .. } => "FootprintLine",
        FootprintGraphic::Rectangle { .. } => "FootprintRectangle",
        FootprintGraphic::Circle { .. } => "FootprintCircle",
        FootprintGraphic::Arc { .. } => "FootprintArc",
        FootprintGraphic::Polygon { .. } => "FootprintPolygon",
    };
    let layer = footprint_layer(graphic.layer(), placement.side);
    let uuid = stable_uuid(&[board_name, "footprint-graphic", &placement.reference, &index.to_string(), class]);
    let stroke = format!("      (stroke (width {}) (type default))", mm(graphic.width_nm()));
    let fill = |filled: bool| format!("      (fill {})", if filled { "solid" } else { "none" });
    let tail = |mut lines: Vec<String>| {
        lines.push(format!("      (layer {})", quote(&layer)));
        lines.push(format!("      (uuid \"{uuid}\")"));
        lines.push("    )".to_owned());
        lines
    };
    match graphic {
        FootprintGraphic::Line { start, end, .. } => tail(vec![
            "    (fp_line".to_owned(),
            format!("      (start {})", point(m(start))),
            format!("      (end {})", point(m(end))),
            stroke,
        ]),
        FootprintGraphic::Rectangle { start, end, filled, .. } => tail(vec![
            "    (fp_rect".to_owned(),
            format!("      (start {})", point(m(start))),
            format!("      (end {})", point(m(end))),
            stroke,
            fill(*filled),
        ]),
        FootprintGraphic::Circle { center, end, filled, .. } => tail(vec![
            "    (fp_circle".to_owned(),
            format!("      (center {})", point(m(center))),
            format!("      (end {})", point(m(end))),
            stroke,
            fill(*filled),
        ]),
        FootprintGraphic::Arc { start, midpoint, end, .. } => tail(vec![
            "    (fp_arc".to_owned(),
            format!("      (start {})", point(m(start))),
            format!("      (mid {})", point(m(midpoint))),
            format!("      (end {})", point(m(end))),
            stroke,
            "      (fill none)".to_owned(),
        ]),
        FootprintGraphic::Polygon { points, filled, .. } => {
            let points: Vec<String> = points.iter().map(|p| format!("(xy {})", point(m(p)))).collect();
            tail(vec!["    (fp_poly".to_owned(), format!("      (pts {})", points.join(" ")), stroke, fill(*filled)])
        }
    }
}

fn pad_lines(
    board_name: &str,
    placement: &Placement,
    pad: &FootprintPad,
    index: usize,
    net: Option<&str>,
    net_codes: &IndexMap<String, usize>,
) -> Vec<String> {
    let back = placement.side == BoardSide::Back;
    let position = if back { Point::new(pad.position.x_nm, -pad.position.y_nm) } else { pad.position };
    let rotation = if back { pad.rotation_degrees.neg().expect("finite") } else { pad.rotation_degrees.clone() };
    let kind = match pad.kind {
        PadKind::Smd if pad.connector_contact => "connect",
        PadKind::Smd | PadKind::Aperture => "smd",
        PadKind::ThroughHole => "thru_hole",
        PadKind::NonPlatedThroughHole => "np_thru_hole",
    };
    let shape = match pad.shape {
        PadShape::Circle => "circle",
        PadShape::Oval => "oval",
        PadShape::Rectangle => "rect",
        PadShape::Roundrect => "roundrect",
    };
    let mut layers: Vec<String> = Vec::new();
    if matches!(pad.kind, PadKind::Smd | PadKind::Aperture) {
        let side = if back { "B" } else { "F" };
        if pad.kind != PadKind::Aperture {
            layers.push(format!("{side}.Cu"));
        }
        if pad.has_solder_paste {
            layers.push(format!("{side}.Paste"));
        }
        if pad.has_solder_mask {
            layers.push(format!("{side}.Mask"));
        }
    } else {
        layers.push("*.Cu".to_owned());
        if pad.has_solder_mask {
            layers.push("*.Mask".to_owned());
        }
    }
    let layers: Vec<String> = layers.iter().map(|l| quote(l)).collect();
    let angle = rotation.add(&placement_rotation(placement)).expect("finite");
    let angle = crate::decimal_rem(&angle, 360).expect("finite");
    let mut lines = vec![
        format!("    (pad {} {kind} {shape}", quote(&pad.number)),
        format!("      (at {} {})", point(position), decimal(&angle)),
        format!("      (size {} {})", mm(pad.size.width_nm), mm(pad.size.height_nm)),
    ];
    if let Some(drill) = pad.drill {
        if drill.width_nm == drill.height_nm {
            lines.push(format!("      (drill {})", mm(drill.width_nm)));
        } else {
            lines.push(format!("      (drill oval {} {})", mm(drill.width_nm), mm(drill.height_nm)));
        }
    }
    lines.push(format!("      (layers {})", layers.join(" ")));
    if pad.shape == PadShape::Roundrect {
        lines.push(format!("      (roundrect_rratio {})", ratio(pad.roundrect_ratio_ppm)));
    }
    if pad.heatsink {
        lines.push("      (property pad_prop_heatsink)".to_owned());
    }
    if let Some(connection) = pad.zone_connection {
        let code = match connection {
            ZoneConnection::None => "1",
            ZoneConnection::Thermal => "2",
            ZoneConnection::Solid => "3",
            ZoneConnection::ThtThermal => "4",
        };
        lines.push(format!("      (zone_connect {code})"));
    }
    if pad.remove_unused_layers {
        lines.push("      (remove_unused_layers yes)".to_owned());
    }
    if let Some(net) = net
        && pad.kind.is_electrical()
    {
        lines.push(format!("      (net {} {})", net_codes[net], quote(net)));
    }
    lines.push("      (pintype \"passive\")".to_owned());
    lines.push(format!(
        "      (uuid \"{}\")",
        stable_uuid(&[board_name, "pad", &placement.reference, &index.to_string(), &pad.number])
    ));
    lines.push("    )".to_owned());
    lines
}

fn component_height(board: &PhysicalBoard, placement: &Placement) -> Option<i64> {
    board
        .component_heights
        .iter()
        .find(|h| h.reference == placement.reference)
        .map(|h| h.height_nm)
        .or(board.footprints[&placement.footprint].height_nm)
}

#[allow(clippy::too_many_arguments)]
fn footprint_lines(
    board: &PhysicalBoard,
    placement: &Placement,
    footprint: &PhysicalFootprint,
    pad_nets: &IndexMap<PadReference, String>,
    net_codes: &IndexMap<String, usize>,
    export_name: &str,
    board_name: &str,
    library: bool,
) -> Vec<String> {
    let board_name = if library { board_name } else { board.name.as_str() };
    let front = placement.side == BoardSide::Front;
    let fab = if front { "F.Fab" } else { "B.Fab" };
    let mut lines = vec![format!("  (footprint {}", quote(export_name))];
    let materialized_member = board.rigid_clusters.iter().any(|cluster| {
        board.materialized_macros.contains(&cluster.name)
            && cluster.members.iter().any(|m| m.reference == placement.reference)
    });
    if materialized_member {
        lines.push("    (locked yes)".to_owned());
    }
    lines.push(format!("    (layer {})", quote(if front { "F.Cu" } else { "B.Cu" })));
    lines.push(format!("    (uuid \"{}\")", stable_uuid(&[board_name, "footprint", &placement.reference])));
    lines.push(format!("    (at {} {})", point(placement.position), decimal(&placement_rotation(placement))));
    let half = footprint.body_size.height_nm.div_euclid(2);
    lines.extend(property_lines(
        board_name,
        &placement.reference,
        "Reference",
        &kicad_reference(&placement.reference),
        0,
        -(half + 1_500_000),
        fab,
        false,
    ));
    lines.extend(property_lines(
        board_name,
        &placement.reference,
        "Value",
        &placement.value,
        0,
        half + 1_500_000,
        fab,
        true,
    ));
    if let Some(height) = component_height(board, placement) {
        lines.extend(property_lines(
            board_name,
            &placement.reference,
            "CopperScriptHeightMM",
            &mm(height),
            0,
            0,
            fab,
            true,
        ));
    }
    if let Some(path) = &placement.source_path
        && !path.is_empty()
    {
        lines.extend(property_lines(board_name, &placement.reference, "CopperScriptPath", path, 0, 0, fab, true));
    }
    let attribute = if footprint
        .pads
        .iter()
        .all(|p| matches!(p.kind, PadKind::Smd | PadKind::Aperture | PadKind::NonPlatedThroughHole))
    {
        "smd"
    } else {
        "through_hole"
    };
    let exclusions = format!(
        "{}{}",
        if footprint.exclude_from_bom { " exclude_from_bom" } else { "" },
        if footprint.exclude_from_pos_files { " exclude_from_pos_files" } else { "" }
    );
    lines.push(format!("    (attr {attribute}{exclusions})"));
    if !footprint.internal_pad_groups.is_empty() {
        lines.push("    (duplicate_pad_numbers_are_jumpers no)".to_owned());
        let groups: Vec<String> = footprint
            .internal_pad_groups
            .iter()
            .map(|g| format!("({})", g.numbers.iter().map(|n| quote(n)).collect::<Vec<_>>().join(" ")))
            .collect();
        lines.push(format!("    (jumper_pad_groups {})", groups.join(" ")));
    }
    if let Some(clearance) = footprint.clearance_nm {
        lines.push(format!("    (clearance {})", mm(clearance)));
    }
    if footprint.graphics.is_empty() {
        let (w, h) = (footprint.body_size.width_nm.div_euclid(2), footprint.body_size.height_nm.div_euclid(2));
        let outline = FootprintGraphic::Rectangle {
            start: Point::new(-w, -h),
            end: Point::new(w, h),
            width_nm: 150_000,
            layer: FootprintLayer::Silkscreen,
            filled: false,
        };
        lines.extend(graphic_lines(board_name, placement, &outline, 0));
    } else {
        for (index, graphic) in footprint.graphics.iter().enumerate() {
            lines.extend(graphic_lines(board_name, placement, graphic, index));
        }
    }
    for (index, pad) in footprint.pads.iter().enumerate() {
        let net = pad_nets.get(&PadReference::new(&placement.reference, &pad.number)).map(String::as_str);
        lines.extend(pad_lines(board_name, placement, pad, index, net, net_codes));
    }
    let mut keepouts: Vec<&CopperKeepout> = footprint.keepouts.iter().collect();
    keepouts.sort_by(|a, b| a.id.cmp(&b.id));
    for local in keepouts {
        let vertices: Vec<Point> =
            local.vertices.iter().map(|p| crate::transform::transformed_local_point(placement, *p)).collect();
        let mut layers = local.layers.clone();
        layers.sort_by_key(|l| l.value());
        for layer in layers {
            let layer = if placement.side == BoardSide::Back {
                match layer {
                    CopperLayer::Front => CopperLayer::Back,
                    CopperLayer::Back => CopperLayer::Front,
                    other => other,
                }
            } else {
                layer
            };
            let identity = format!("{}/{}", placement.reference, local.id);
            lines.extend(copper_keepout_lines(board_name, local, &vertices, layer, &identity, true));
        }
    }
    lines.push("  )".to_owned());
    lines
}

fn silkscreen_lines(board_name: &str, item: &Artwork, mask: bool) -> Vec<String> {
    let copper = artwork_layer(item);
    let (id, side) = match item {
        Artwork::Text { id, side, .. } | Artwork::Graphic { id, side, .. } => (id.as_str(), *side),
    };
    let prefix = if side == BoardSide::Front { "F" } else { "B" };
    let layer = if mask {
        format!("{prefix}.Mask")
    } else {
        copper.map_or_else(|| format!("{prefix}.SilkS"), |l| l.value().to_owned())
    };
    let identity = if mask {
        stable_uuid(&[board_name, "silkscreen", id, "mask"])
    } else {
        stable_uuid(&[board_name, "silkscreen", id])
    };
    let locked: Vec<String> = if copper.is_some() && !mask { vec!["    (locked yes)".to_owned()] } else { Vec::new() };
    match item {
        Artwork::Text { text, position, size_nm, thickness_nm, rotation_degrees, .. } => {
            let justify = if side == BoardSide::Back { " (justify mirror)" } else { "" };
            let mut lines = vec![
                format!("  (gr_text {}", quote(text)),
                format!("    (at {} {})", point(*position), decimal(&rotation_degrees.neg().expect("finite"))),
                format!("    (layer {})", quote(&layer)),
            ];
            lines.extend(locked);
            lines.push(format!("    (uuid \"{identity}\")"));
            lines.push(format!(
                "    (effects (font (size {} {}) (thickness {})){justify})",
                mm(*size_nm),
                mm(*size_nm),
                mm(*thickness_nm)
            ));
            lines.push("  )".to_owned());
            lines
        }
        Artwork::Graphic { graphic, .. } => {
            let (kind, geometry, filled, width) = match graphic {
                Graphic::Line { start, end, width_nm } => (
                    "line",
                    vec![format!("(start {})", point(*start)), format!("(end {})", point(*end))],
                    None,
                    *width_nm,
                ),
                Graphic::Rectangle { start, end, width_nm, filled } => (
                    "rect",
                    vec![format!("(start {})", point(*start)), format!("(end {})", point(*end))],
                    Some(*filled),
                    *width_nm,
                ),
                Graphic::Circle { center, end, width_nm, filled } => (
                    "circle",
                    vec![format!("(center {})", point(*center)), format!("(end {})", point(*end))],
                    Some(*filled),
                    *width_nm,
                ),
                Graphic::Arc { start, midpoint, end, width_nm } => (
                    "arc",
                    vec![
                        format!("(start {})", point(*start)),
                        format!("(mid {})", point(*midpoint)),
                        format!("(end {})", point(*end)),
                    ],
                    None,
                    *width_nm,
                ),
                Graphic::Polygon { points, width_nm, filled } => {
                    let pts: Vec<String> = points.iter().map(|p| format!("(xy {})", point(*p))).collect();
                    ("poly", vec![format!("(pts {})", pts.join(" "))], Some(*filled), *width_nm)
                }
            };
            let mut lines = vec![format!("  (gr_{kind}")];
            lines.extend(geometry.into_iter().map(|line| format!("    {line}")));
            lines.push(format!("    (stroke (width {}) (type default))", mm(width)));
            if let Some(filled) = filled {
                lines.push(format!("    (fill {})", if filled { "solid" } else { "none" }));
            }
            lines.push(format!("    (layer {})", quote(&layer)));
            lines.extend(locked);
            lines.push(format!("    (uuid \"{identity}\")"));
            lines.push("  )".to_owned());
            lines
        }
    }
}

/// `resolved_cluster_keepouts`: cluster-local keepouts at their anchors' poses.
fn resolved_cluster_keepouts(board: &PhysicalBoard) -> Vec<(String, CopperKeepout, Vec<Point>)> {
    let mut result = Vec::new();
    for cluster in &board.rigid_clusters {
        let Some(anchor) = board.placements.iter().find(|p| p.reference == cluster.anchor_reference) else { continue };
        let local = cluster.members.iter().find(|m| m.reference == anchor.reference).expect("anchor member");
        let origin =
            crate::transform::transformed_local_point(anchor, Point::new(-local.position.x_nm, -local.position.y_nm));
        let frame = Placement { position: origin, ..anchor.clone() };
        for keepout in &cluster.keepouts {
            let vertices =
                keepout.vertices.iter().map(|p| crate::transform::transformed_local_point(&frame, *p)).collect();
            result.push((format!("cluster/{}/{}", cluster.name, keepout.id), keepout.clone(), vertices));
        }
    }
    result
}

fn render(board: &PhysicalBoard, library_names: &IndexMap<String, String>) -> Result<String> {
    let poses = crate::keepouts::placement_map(board);
    let (mut macro_tracks, mut macro_vias, mut macro_zone_ids) = (Vec::new(), Vec::new(), Vec::new());
    for hard in board.hard_macros.iter().filter(|m| board.materialized_macros.contains(&m.cluster)) {
        let geometry = crate::hard_macros::resolved_macro_geometry(board, hard, &poses)?;
        macro_tracks.extend(geometry.tracks);
        macro_vias.extend(geometry.vias);
        macro_zone_ids.extend(crate::hard_macros::resolved_macro_zones(board, hard, &poses)?.into_iter().map(|z| z.id));
    }
    let mut nets: Vec<&PhysicalNet> = board.nets.iter().collect();
    nets.sort_by(|a, b| a.name.cmp(&b.name));
    let net_codes: IndexMap<String, usize> = nets.iter().enumerate().map(|(i, n)| (n.name.clone(), i + 1)).collect();
    let pad_nets: IndexMap<PadReference, String> =
        board.nets.iter().flat_map(|n| n.pads.iter().map(move |p| (p.clone(), n.name.clone()))).collect();
    let version =
        if uses_internal_connections(board) || !board.polygons.is_empty() { "20260206" } else { KICAD_PCB_FORMAT };
    let mut lines: Vec<String> = vec![
        "(kicad_pcb".to_owned(),
        format!("  (version {version})"),
        "  (generator \"copperscript\")".to_owned(),
        "  (generator_version \"0.1.0\")".to_owned(),
        "  (general".to_owned(),
        format!("    (thickness {})", mm(board.stackup.thickness_nm)),
        "  )".to_owned(),
        "  (paper \"A4\")".to_owned(),
        "  (layers".to_owned(),
    ];
    lines.extend(copper_layer_lines(board));
    for line in [
        "    (32 \"B.Adhes\" user \"B.Adhesive\")",
        "    (33 \"F.Adhes\" user \"F.Adhesive\")",
        "    (34 \"B.Paste\" user)",
        "    (35 \"F.Paste\" user)",
        "    (36 \"B.SilkS\" user \"b.silkscreen\")",
        "    (37 \"F.SilkS\" user \"f.silkscreen\")",
        "    (38 \"B.Mask\" user)",
        "    (39 \"F.Mask\" user)",
        "    (44 \"Edge.Cuts\" user)",
        "    (46 \"B.CrtYd\" user \"B.Courtyard\")",
        "    (47 \"F.CrtYd\" user \"F.Courtyard\")",
        "    (48 \"B.Fab\" user)",
        "    (49 \"F.Fab\" user)",
        "  )",
        "  (setup",
    ] {
        lines.push(line.to_owned());
    }
    lines.extend(stackup_lines(board));
    lines.extend([
        "    (pad_to_mask_clearance 0)".to_owned(),
        "    (allow_soldermask_bridges_in_footprints no)".to_owned(),
        "  )".to_owned(),
        "  (net 0 \"\")".to_owned(),
    ]);
    for (name, code) in &net_codes {
        lines.push(format!("  (net {code} {})", quote(name)));
    }
    let mut placements: Vec<&Placement> = board.placements.iter().collect();
    placements.sort_by(|a, b| a.reference.cmp(&b.reference));
    for placement in placements {
        let footprint = &board.footprints[&placement.footprint];
        let export = format!("{GENERATED_LIBRARY}:{}", library_names[&placement.footprint]);
        lines.extend(footprint_lines(board, placement, footprint, &pad_nets, &net_codes, &export, &board.name, false));
    }
    for (index, track) in board.tracks.iter().enumerate() {
        lines.push("  (segment".to_owned());
        if macro_tracks.contains(track) {
            lines.push("    (locked yes)".to_owned());
        }
        lines.extend([
            format!("    (start {})", point(track.start)),
            format!("    (end {})", point(track.end)),
            format!("    (width {})", mm(track.width_nm)),
            format!("    (layer {})", quote(track.layer.value())),
            format!("    (net {})", net_codes[&track.net]),
            format!("    (uuid \"{}\")", stable_uuid(&[&board.name, "segment", &index.to_string()])),
            "  )".to_owned(),
        ]);
    }
    for (index, via) in board.vias.iter().enumerate() {
        // No source declares via technologies, so every via is a through via.
        lines.push("  (via".to_owned());
        if macro_vias.contains(via) {
            lines.push("    (locked yes)".to_owned());
        }
        lines.extend([
            format!("    (at {})", point(via.position)),
            format!("    (size {})", mm(via.size_nm)),
            format!("    (drill {})", mm(via.drill_nm)),
            format!("    (layers {} {})", quote(via.from_layer.value()), quote(via.to_layer.value())),
            format!("    (net {})", net_codes[&via.net]),
            format!("    (uuid \"{}\")", stable_uuid(&[&board.name, "via", &index.to_string()])),
            "  )".to_owned(),
        ]);
    }
    let mut polygons: Vec<&CopperPolygon> = board.polygons.iter().collect();
    polygons.sort_by(|a, b| a.id.cmp(&b.id));
    for polygon in polygons {
        let points: Vec<String> = polygon.vertices.iter().map(|p| format!("(xy {})", point(*p))).collect();
        lines.extend([
            "  (gr_poly".to_owned(),
            format!("    (pts {})", points.join(" ")),
            "    (stroke (width 0) (type default))".to_owned(),
            "    (fill yes)".to_owned(),
            format!("    (layer {})", quote(polygon.layer.value())),
            format!("    (net {})", net_codes[&polygon.net]),
            "    (locked yes)".to_owned(),
            format!("    (uuid \"{}\")", stable_uuid(&[&board.name, "polygon", &polygon.id])),
            "  )".to_owned(),
        ]);
    }
    let mut zones: Vec<&CopperZone> = board.zones.iter().collect();
    zones.sort_by(|a, b| b.priority.cmp(&a.priority).then_with(|| a.id.cmp(&b.id)));
    for zone in zones {
        let mut layers = zone.layers.clone();
        layers.sort_by_key(|l| l.value());
        for layer in layers {
            lines.extend(zone_lines(board, zone, layer, &net_codes, macro_zone_ids.contains(&zone.id))?);
        }
    }
    let mut keepouts: Vec<(String, CopperKeepout, Vec<Point>)> =
        board.copper_keepouts.iter().map(|k| (k.id.clone(), k.clone(), k.vertices.clone())).collect();
    keepouts.extend(resolved_cluster_keepouts(board));
    keepouts.sort_by(|a, b| a.0.cmp(&b.0));
    for (id, keepout, vertices) in &keepouts {
        let mut layers = keepout.layers.clone();
        layers.sort_by_key(|l| l.value());
        let named = CopperKeepout { id: id.clone(), ..keepout.clone() };
        for layer in layers {
            lines.extend(copper_keepout_lines(&board.name, &named, vertices, layer, id, false));
        }
    }
    let mut artwork: Vec<&Artwork> = board.silkscreen.iter().collect();
    artwork.sort_by(|a, b| a.id().cmp(b.id()));
    for item in artwork {
        lines.extend(silkscreen_lines(&board.name, item, false));
        let exposed = match item {
            Artwork::Text { exposed, .. } | Artwork::Graphic { exposed, .. } => *exposed,
        };
        if exposed {
            lines.extend(silkscreen_lines(&board.name, item, true));
        }
    }
    let outline = &board.outline;
    if let Some(circle) = outline.circular_boundary {
        lines.extend([
            "  (gr_circle".to_owned(),
            format!("    (center {})", point(circle.center)),
            format!("    (end {})", point(Point::new(circle.center.x_nm + circle.radius_nm, circle.center.y_nm))),
            "    (stroke (width 0.05) (type default))".to_owned(),
            "    (fill none)".to_owned(),
            "    (layer \"Edge.Cuts\")".to_owned(),
            format!("    (uuid \"{}\")", stable_uuid(&[&board.name, "outline", "circle"])),
            "  )".to_owned(),
        ]);
    }
    if let Some(path) = &outline.boundary_path {
        for segment in &path.segments {
            match segment {
                BoundarySegment::Line { id, start, end } => lines.extend([
                    "  (gr_line".to_owned(),
                    format!("    (start {})", point(*start)),
                    format!("    (end {})", point(*end)),
                    "    (stroke (width 0.05) (type default))".to_owned(),
                    "    (layer \"Edge.Cuts\")".to_owned(),
                    format!("    (uuid \"{}\")", stable_uuid(&[&board.name, "outline", id])),
                    "  )".to_owned(),
                ]),
                BoundarySegment::Arc { id, start, mid, end } => lines.extend([
                    "  (gr_arc".to_owned(),
                    format!("    (start {})", point(*start)),
                    format!("    (mid {})", point(*mid)),
                    format!("    (end {})", point(*end)),
                    "    (stroke (width 0.05) (type default))".to_owned(),
                    "    (layer \"Edge.Cuts\")".to_owned(),
                    format!("    (uuid \"{}\")", stable_uuid(&[&board.name, "outline", id])),
                    "  )".to_owned(),
                ]),
            }
        }
    }
    let mut loops: Vec<(String, &[Point])> = Vec::new();
    if outline.circular_boundary.is_none() && outline.boundary_path.is_none() {
        loops.push(("outer".to_owned(), &outline.vertices));
    }
    for cutout in &outline.cutouts {
        loops.push((format!("cutout:{}", cutout.id), &cutout.vertices));
    }
    for (loop_id, vertices) in loops {
        for (index, start) in vertices.iter().enumerate() {
            let end = vertices[(index + 1) % vertices.len()];
            lines.extend([
                "  (gr_line".to_owned(),
                format!("    (start {})", point(*start)),
                format!("    (end {})", point(end)),
                "    (stroke (width 0.05) (type default))".to_owned(),
                "    (layer \"Edge.Cuts\")".to_owned(),
                format!("    (uuid \"{}\")", stable_uuid(&[&board.name, "outline", &loop_id, &index.to_string()])),
                "  )".to_owned(),
            ]);
        }
    }
    lines.push(")".to_owned());
    Ok(lines.join("\n") + "\n")
}
