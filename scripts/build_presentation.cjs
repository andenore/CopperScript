#!/usr/bin/env node
/* Build a slide deck kept as source under docs/presentations/NAME/ into a
   standalone index.html (one 1920x1080 slide at a time, arrow keys, N shows
   the speaker notes, prints one slide per page) and, with --pdf, NAME.pdf.

   node scripts/build_presentation.cjs docs/presentations/copperscript-overview [--pdf]

   The deck folder holds deck.json (title, slide order, font links), deck.css
   (shared rules), slides/ID.html (one <section> each, notes in its <aside>)
   and assets/. The PDF needs the pre-installed Playwright and Chromium and
   network access to Google Fonts. */
"use strict";
const fs = require("node:fs"), path = require("node:path");

const USAGE = "usage: build_presentation.cjs DECK_DIR [--pdf]";
const escapeHtml = text => text.replace(/[&<>"]/g, c => ({"&": "&amp;", "<": "&lt;", ">": "&gt;", "\"": "&quot;"})[c]);

// Slides draws these elements itself; a browser needs plain CSS for them.
const VIEWER_CSS = `
html,body{margin:0;height:100%;background:#0f1514}
section{width:1920px;height:1080px;box-sizing:border-box;overflow:hidden;position:relative}
x-shape{display:block}
table{border-collapse:collapse}
th,td{padding:.35em .6em;border-bottom:1px solid rgba(127,127,127,.35);vertical-align:top}
x-shape[kind="arrow-right"]{clip-path:polygon(0 30%,60% 30%,60% 0,100% 50%,60% 100%,60% 70%,0 70%)}
aside{display:none}
.deck{position:fixed;inset:0;display:flex;align-items:center;justify-content:center}
.deck section{position:absolute;left:50%;top:50%;transform-origin:center;display:none}
.deck section.current{display:flex}
.bar{position:fixed;left:0;right:0;bottom:0;display:flex;justify-content:space-between;gap:16px;padding:8px 16px;font:13px Arial,sans-serif;color:#b9c4bf;background:rgba(15,21,20,.85)}
.notes{position:fixed;left:0;right:0;bottom:34px;max-height:30vh;overflow:auto;padding:12px 16px;font:15px/1.5 Arial,sans-serif;color:#f4f1ea;background:rgba(15,21,20,.95);display:none}
body.show-notes .notes{display:block}
@media print{
  @page{size:1920px 1080px;margin:0}
  html,body{background:none}
  .bar,.notes{display:none!important}
  .deck{position:static;display:block}
  .deck section{position:relative;left:auto;top:auto;transform:none!important;display:flex!important;break-after:page}
  *{animation:none!important;transition:none!important}
}`;

const VIEWER_JS = `
const slides=[...document.querySelectorAll('.deck section')];
const counter=document.getElementById('counter'), notes=document.getElementById('notes');
let index=Math.max(0,Math.min(slides.length-1,(parseInt(location.hash.slice(1),10)||1)-1));
function fit(){const s=Math.min(innerWidth/1920,(innerHeight-34)/1080);for(const el of slides)el.style.transform='translate(-50%,calc(-50% - 17px)) scale('+s+')';}
function show(i){index=Math.max(0,Math.min(slides.length-1,i));slides.forEach((el,k)=>el.classList.toggle('current',k===index));
  counter.textContent=(index+1)+' / '+slides.length;const aside=slides[index].querySelector('aside');notes.textContent=aside?aside.textContent:'No notes.';history.replaceState(null,'','#'+(index+1));}
addEventListener('keydown',e=>{if(['ArrowRight','PageDown',' '].includes(e.key))show(index+1);else if(['ArrowLeft','PageUp'].includes(e.key))show(index-1);
  else if(e.key==='Home')show(0);else if(e.key==='End')show(slides.length-1);else if(e.key==='n'||e.key==='N')document.body.classList.toggle('show-notes');});
document.querySelector('.deck').addEventListener('click',e=>show(index+(e.clientX>innerWidth/2?1:-1)));
addEventListener('resize',fit);fit();show(index);`;

function build(dir) {
  const deck = JSON.parse(fs.readFileSync(path.join(dir, "deck.json"), "utf8"));
  const css = fs.readFileSync(path.join(dir, "deck.css"), "utf8");
  const fonts = [...new Set(Object.values(deck.faces || {}).map(face => face.href).filter(Boolean))];
  const sections = deck.order.map(id => {
    const html = fs.readFileSync(path.join(dir, "slides", `${id}.html`), "utf8").trim();
    if (!html.startsWith(`<section id="${id}"`)) throw new Error(`slides/${id}.html: expected one <section id="${id}">`);
    return html;
  });
  const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(deck.title)}</title>
${fonts.map(href => `<link rel="stylesheet" href="${escapeHtml(href)}">`).join("\n")}
<!-- Generated by scripts/build_presentation.cjs from deck.json, deck.css and slides/. Do not edit. -->
<style>
${css}
${VIEWER_CSS}
</style>
</head>
<body>
<main class="deck">
${sections.join("\n")}
</main>
<div class="notes" id="notes" aria-live="polite"></div>
<div class="bar"><span>${escapeHtml(deck.title)}</span><span>← → to move · N for notes</span><span id="counter"></span></div>
<script>${VIEWER_JS}</script>
</body>
</html>
`;
  const output = path.join(dir, "index.html");
  fs.writeFileSync(output, page);
  return {deck, output};
}

async function pdf(dir, deck, index) {
  const {chromium} = require("playwright");
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({viewport: {width: 1920, height: 1080}});
    await page.goto(`file://${path.resolve(index)}`, {waitUntil: "networkidle"});
    await page.evaluate(() => document.fonts.ready);
    const name = path.join(dir, `${path.basename(path.resolve(dir))}.pdf`);
    await page.pdf({path: name, width: "1920px", height: "1080px", printBackground: true, preferCSSPageSize: true});
    return name;
  } finally {
    await browser.close();
  }
}

(async () => {
  const args = process.argv.slice(2);
  const dir = args.find(a => !a.startsWith("--"));
  if (!dir || args.some(a => a.startsWith("--") && a !== "--pdf")) throw new Error(USAGE);
  const {deck, output} = build(dir);
  console.log(`${deck.order.length} slides -> ${output}`);
  if (args.includes("--pdf")) console.log(`PDF -> ${await pdf(dir, deck, output)}`);
})().catch(error => { console.error(error.message); process.exit(2); });
